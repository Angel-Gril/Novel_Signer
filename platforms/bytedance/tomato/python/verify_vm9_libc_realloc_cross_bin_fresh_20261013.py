BASES=dependency.BASES;LIBC=dependency.LIBC;TP=dependency.WORKER_TLS;G=dependency.GUEST
PROFILES=((8,32),(16,64),(32,64),(32,8),(48,128),(64,32),(128,256),(256,128))


def native(p,pointer,size):
 c=Uc(UC_ARCH_ARM64,UC_MODE_ARM)
 for page,data in p.items():c.mem_map(page<<12,4096);c.mem_write(page<<12,bytes(data))
 for r,v in ((arm.UC_ARM64_REG_X0,pointer),(arm.UC_ARM64_REG_X1,size),(arm.UC_ARM64_REG_X30,dependency.STOP),
  (arm.UC_ARM64_REG_SP,G+0xEF00),(arm.UC_ARM64_REG_TPIDR_EL0,TP)):c.reg_write(r,v)
 entries=[]
 def observe(c,a,n,u):
  if a-LIBC in (0x1BB88,0x90420,0x7BB80,0x7B2C8,0x176E0):entries.append(hex(a-LIBC))
 def interrupt(*a):raise AssertionError('cross-bin control unexpectedly issued syscall')
 c.hook_add(UC_HOOK_CODE,observe);c.hook_add(UC_HOOK_INTR,interrupt)
 c.emu_start(LIBC+0x1BB88,dependency.STOP,count=300000)
 assert c.reg_read(arm.UC_ARM64_REG_PC)==dependency.STOP and entries[:2]==['0x1bb88','0x90420']
 observed={page:bytes(c.mem_read(page<<12,4096)) for page in p if not G+0xE000<=page<<12<G+0xF000}
 return c.reg_read(arm.UC_ARM64_REG_X0),observed,entries


def session(p,base):
 def os_call(tx,op,*args):raise AssertionError('cross-bin model unexpectedly requested '+op)
 return ActualAllocatorSession(allocator.GuestOS(p),image_base=base,libc_base=LIBC,thread_pointer=TP,
  scratch_address=G+0xC000,brk=lambda *a:0x13600000,os_call=os_call,once_wake=lambda *a:0,
  register_destructor=lambda *a:0,thread_id=137)


def red(library,libc):
 assert not hasattr(model,'reallocate_small_bins');rows=[]
 for base in BASES:
  p,pointer,width=dependency.seed(library,libc,base,32);returned,observed,entries=native(p,pointer,64)
  assert returned and returned!=pointer
  before={k:bytes(v) for k,v in p.items()}
  try:session(p,base).reallocate(p,pointer,64)
  except allocator.RefillUnsupported as exc:assert str(exc)=='matching-libc cross-bin realloc is unrecovered'
  else:raise AssertionError('RED requires old rejection')
  assert before=={k:bytes(v) for k,v in p.items()}
  rows.append(dict(image_base=hex(base),original_cross_bin_realloc_returned=True,
   prior_session_cross_bin_rejected=True,native_snapshot_input=False))
 return rows


def compare(library,libc,base,old,new,overflow=False):
 p,pointer,width=dependency.seed(library,libc,base,old)
 if overflow:_w(p,LIBC+0xDB6B8+0x18,(1<<64)-3);_w(p,LIBC+0xDB6B8+0x20,(1<<64)-5)
 returned,observed,entries=native(p,pointer,new);own=session(p,base);p=own.pages
 result=own.reallocate(p,pointer,new)
 assert result==returned and result!=pointer
 differences=[(hex(k<<12),next((hex(i) for i,(a,b) in enumerate(zip(p[k],data)) if a!=b),None)) for k,data in observed.items() if bytes(p[k])!=data]
 assert not differences,(old,new,differences[:8])
 print('PASS cross-bin realloc',hex(base),old,new,overflow,flush=True)
 return dict(image_base=hex(base),old_request=old,new_request=new,old_usable_size=width,wrapping_statistics=overflow,
  original_export_and_allocator_returned=True,new_pointer_and_all_non_stack_pages_equal=True,
  payload_metadata_cache_and_TSD_statistics_equal=True,native_body_offsets=entries,native_snapshot_input=False)


def guards(library,libc):
 rows=[]
 for label in ('NULL_pointer','zero_size','oversized','profiling','interior','already_cached','unmapped_payload','allocate_failure','free_failure'):
  base=BASES[0];p,pointer,width=dependency.seed(library,libc,base,32)
  if label=='unmapped_payload':p.pop(pointer>>12)
  own=session(p,base);p=own.pages;size=64
  kw=dict(pointer=pointer,request_size=size,libc_base=LIBC,thread_pointer=TP,allocate=own.allocate,free=own.free)
  if label=='NULL_pointer':kw['pointer']=0
  elif label=='zero_size':kw['request_size']=0
  elif label=='oversized':kw['request_size']=0x4000
  elif label=='profiling':_w(p,LIBC+0xE69C0,1)
  elif label=='interior':kw['pointer']=pointer+1
  elif label=='already_cached':own.free(p,pointer)
  elif label=='allocate_failure':
   def fail(p,n):allocator._write_span(p,pointer,b'bad');raise allocator.RefillUnsupported('allocate failed')
   kw['allocate']=fail
  elif label=='free_failure':
   def fail(p,a):allocator._write_span(p,pointer,b'bad');raise allocator.RefillUnsupported('free failed')
   kw['free']=fail
  before={k:bytes(v) for k,v in p.items()}
  try:model.reallocate_small_bins(p,**kw)
  except (allocator.RefillUnsupported,ValueError):pass
  else:raise AssertionError(label)
  assert before=={k:bytes(v) for k,v in p.items()}
  rows.append(dict(case=label,rejected=True,all_pages_unchanged=True,external_provider_rollback_verified=False))
 return rows


